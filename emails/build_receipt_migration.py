"""Writes a migration that loads the receipt templates from this folder into the database (task-10-6).

Usage: python3 emails/build_receipt_migration.py <migration-name>
Edit eingangsbestaetigung.html / .txt, then generate a new migration with this script.
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent
html = (root / "eingangsbestaetigung.html").read_text(encoding="utf-8")
text = (root / "eingangsbestaetigung.txt").read_text(encoding="utf-8")
for name, body in (("html", html), ("text", text)):
    if "$tpl$" in body:
        sys.exit(f"{name} template must not contain $tpl$")

fill = """  select replace(replace(replace(replace(replace(replace(replace(replace(replace(template,
    '{{{{request_number}}}}', {e}(req.request_number)),
    '{{{{contact_name}}}}', {e}(req.contact_name)),
    '{{{{company_name}}}}', {e}(req.company_name)),
    '{{{{street}}}}', {e}(req.street_house_number)),
    '{{{{postal_code}}}}', {e}(req.postal_code)),
    '{{{{city}}}}', {e}(req.city)),
    '{{{{service_kind}}}}', {e}(private.receipt_service_label(req.service_kind))),
    '{{{{preferred_date}}}}', {e}(coalesce(to_char(req.requested_visit_date, 'DD.MM.YYYY'), 'keine Angabe'))),
    '{{{{customer_number_note}}}}', private.customer_number_note_{note}(req.customer_number))"""

sql = f"""-- Designed receipt e-mail (task-10-6): HTML and plain text from emails/eingangsbestaetigung.*,
-- generated by emails/build_receipt_migration.py. Customer input is HTML-escaped in the HTML part.
-- {{{{customer_number_note}}}}: customer number only for requests already linked to a customer (task-15-3).

alter table public.messages add column if not exists body_html text;
comment on column public.messages.body_html is 'Optional HTML part of an outgoing message; body_text stays the plain-text part and the dashboard view.';

create or replace function private.html_escape(value text) returns text
language sql immutable set search_path = '' as $$
  select replace(replace(replace(replace(replace(coalesce(value, ''), '&', '&amp;'), '<', '&lt;'), '>', '&gt;'), '"', '&quot;'), '''', '&#39;')
$$;

create or replace function private.receipt_service_label(kind public.service_kind) returns text
language sql immutable set search_path = '' as $$
  select case kind when 'inspection' then 'Inspektion' when 'scheduled_maintenance' then 'Planmäßige Wartung' else 'Diagnose und Reparatur' end
$$;

create or replace function private.receipt_text(req public.requests) returns text
language sql stable set search_path = '' as $f$
  with t(template) as (select $tpl${text}$tpl$::text)
{fill.format(e='coalesce', note='text')} from t
$f$;

create or replace function private.receipt_html(req public.requests) returns text
language sql stable set search_path = '' as $f$
  with t(template) as (select $tpl${html}$tpl$::text)
{fill.format(e='private.html_escape', note='html')} from t
$f$;

create or replace function private.queue_receipt(req public.requests) returns void
language plpgsql security definer set search_path = '' as $$
declare msg public.messages;
begin
  if req.is_demo or nullif(btrim(req.business_email), '') is null then return; end if;
  insert into public.messages (request_id, direction, kind, status, to_address, subject, body_text, body_html, approved_at)
  values (req.id, 'outgoing', 'receipt', 'queued', req.business_email,
    'Eingangsbestätigung ' || req.request_number || ' · Ihre Serviceanfrage', private.receipt_text(req), private.receipt_html(req), now())
  on conflict (request_id) where kind = 'receipt' do nothing
  returning * into msg;
  if msg.id is null then return; end if;
  insert into public.request_events (request_id, actor_type, event_type, visibility, from_value, to_value, data)
  values (req.id, 'automation', 'message_queued', 'dispatch', null, 'queued',
    jsonb_build_object('message_id', msg.id, 'kind', msg.kind, 'approved_by', 'system'));
end;
$$;

revoke all on function private.html_escape(text), private.receipt_service_label(public.service_kind),
  private.receipt_text(public.requests), private.receipt_html(public.requests), private.queue_receipt(public.requests)
  from public, anon, authenticated;
notify pgrst, 'reload schema';
"""
target = root.parent / "supabase" / "migrations" / f"{sys.argv[1]}.sql"
target.write_text(sql, encoding="utf-8")
print(target)
