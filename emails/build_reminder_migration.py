"""Writes a migration that loads the payment reminder templates from this folder into the database (task-10-2).

Usage: python3 emails/build_reminder_migration.py <migration-name>
Edit zahlungserinnerung.html / .txt, then generate a new migration with this script.
Stage wording (subject, heading, intro, request to pay) lives in private.reminder_values below.
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent
html = (root / "zahlungserinnerung.html").read_text(encoding="utf-8")
text = (root / "zahlungserinnerung.txt").read_text(encoding="utf-8")
for name, body in (("html", html), ("text", text)):
    if "$tpl$" in body:
        sys.exit(f"{name} template must not contain $tpl$")

sql = f"""-- Payment reminder e-mails (task-10-2): HTML and plain text from emails/zahlungserinnerung.*, generated by
-- emails/build_reminder_migration.py. Same design as the receipt; values are HTML-escaped in the HTML part.

-- Replaces every {{{{key}}}} with its value; keys are fixed by private.reminder_values.
create or replace function private.fill_template(template text, vals jsonb, escape_html boolean) returns text
language plpgsql immutable set search_path = '' as $$
declare
  result text := template;
  kv record;
begin
  for kv in select key, value from jsonb_each_text(vals) loop
    result := replace(result, '{{{{' || kv.key || '}}}}',
      case when escape_html and kv.key <> 'accent' then private.html_escape(kv.value) else coalesce(kv.value, '') end);
  end loop;
  return result;
end;
$$;

create or replace function private.reminder_values(inv public.invoices, req public.requests, reminder_stage smallint) returns jsonb
language plpgsql stable set search_path = '' as $$
declare
  nr text := inv.invoice_number;
  issued text := to_char(inv.issue_date, 'DD.MM.YYYY');
  due text := to_char(inv.payment_due_date, 'DD.MM.YYYY');
  overdue integer := greatest(private.local_today() - inv.payment_due_date, 0);
  amount text := replace(replace(replace(to_char(inv.total, 'FM999,999,990.00'), ',', ' '), '.', ','), ' ', '.')
    || case when inv.currency = 'EUR' then ' €' else ' ' || inv.currency end;
  vals jsonb;
begin
  vals := jsonb_build_object(
    'invoice_number', nr, 'issue_date', issued, 'due_date', due, 'amount', amount,
    'overdue_days', overdue || case when overdue = 1 then ' Tag' else ' Tage' end,
    'request_number', req.request_number,
    'contact_name', coalesce(nullif(btrim(inv.customer_snapshot ->> 'contact_name'), ''), req.contact_name),
    'payee', coalesce(inv.seller_snapshot ->> 'company_name', 'RheinWerk Industrieservice GmbH'),
    'iban', coalesce(inv.seller_snapshot ->> 'iban', ''),
    'bank', coalesce(inv.seller_snapshot ->> 'bank', ''));
  vals := vals || case reminder_stage
    when 1 then jsonb_build_object(
      'stage_label', 'ZAHLUNGSERINNERUNG', 'heading', 'Freundliche Zahlungserinnerung', 'accent', '#B7D83D',
      'subject', 'Zahlungserinnerung zu Rechnung ' || nr,
      'intro', 'sicher ist es im Tagesgeschäft untergegangen: Für unsere Rechnung ' || nr || ' vom ' || issued
        || ' haben wir bisher keinen Zahlungseingang verbucht. Der Betrag war am ' || due || ' fällig.',
      'ask', 'Bitte überweisen Sie den offenen Betrag in den nächsten Tagen.')
    when 2 then jsonb_build_object(
      'stage_label', '1. MAHNUNG', 'heading', '1. Mahnung', 'accent', '#D98E04',
      'subject', '1. Mahnung zu Rechnung ' || nr,
      'intro', 'trotz unserer Zahlungserinnerung ist die Rechnung ' || nr || ' vom ' || issued
        || ' weiterhin offen. Der Betrag ist seit dem ' || due || ' fällig.',
      'ask', 'Bitte überweisen Sie den offenen Betrag innerhalb von 7 Tagen.')
    else jsonb_build_object(
      'stage_label', '2. MAHNUNG', 'heading', '2. Mahnung', 'accent', '#C43B31',
      'subject', '2. Mahnung zu Rechnung ' || nr || ' – Zahlungsverzug',
      'intro', 'die Rechnung ' || nr || ' vom ' || issued
        || ' ist trotz Zahlungserinnerung und Mahnung weiterhin offen. Sie befinden sich damit in Zahlungsverzug.',
      'ask', 'Bitte überweisen Sie den offenen Betrag innerhalb von 7 Tagen. Andernfalls behalten wir uns weitere Schritte vor, insbesondere die Berechnung von Verzugszinsen.')
  end;
  return vals || jsonb_build_object('preheader', (vals ->> 'heading') || ': Rechnung ' || nr || ' über ' || amount);
end;
$$;

create or replace function private.reminder_subject(inv public.invoices, reminder_stage smallint) returns text
language sql stable set search_path = '' as $$
  select private.reminder_values(inv, r, reminder_stage) ->> 'subject' from public.requests r where r.id = inv.request_id
$$;

create or replace function private.reminder_text(inv public.invoices, req public.requests, reminder_stage smallint) returns text
language sql stable set search_path = '' as $f$
  select private.fill_template($tpl${text}$tpl$, private.reminder_values(inv, req, reminder_stage), false)
$f$;

create or replace function private.reminder_html(inv public.invoices, req public.requests, reminder_stage smallint) returns text
language sql stable set search_path = '' as $f$
  select private.fill_template($tpl${html}$tpl$, private.reminder_values(inv, req, reminder_stage), true)
$f$;

revoke all on function private.fill_template(text, jsonb, boolean),
  private.reminder_values(public.invoices, public.requests, smallint), private.reminder_subject(public.invoices, smallint),
  private.reminder_text(public.invoices, public.requests, smallint), private.reminder_html(public.invoices, public.requests, smallint)
  from public, anon, authenticated;
"""
target = root.parent / "supabase" / "migrations" / f"{sys.argv[1]}.sql"
target.write_text(sql, encoding="utf-8")
print(target)
