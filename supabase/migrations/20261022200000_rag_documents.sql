-- task-18-10: knowledge base of the website assistant (RAG), moved from the Oracle server into RheinWerk. Sections of
-- the documents in n8n/rag-documents with their OpenAI embeddings (text-embedding-3-large, 3072 dimensions), written
-- by the n8n workflow "RheinWerk · Dokumente importieren" and searched by "RheinWerk · Assistent" (Supabase Vector
-- Store of n8n: table rag_documents, function match_rag_documents). Only service_role (n8n) reads and writes; the
-- website asks through /api/assistant and never touches the table. Without an index: a few dozen rows, and pgvector
-- indexes stop at 2000 dimensions.

create extension if not exists vector with schema extensions;

create table public.rag_documents (
  id bigint generated by default as identity primary key,
  content text not null,
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata) = 'object'),
  embedding extensions.vector(3072) not null,
  created_at timestamptz not null default now()
);
comment on table public.rag_documents is 'Wissensbasis des Website-Assistenten (task-18-10): Abschnitte aus n8n/rag-documents mit Embedding; metadata.file = Quelldatei';

alter table public.rag_documents enable row level security;
revoke all on public.rag_documents from anon, authenticated;
grant all on public.rag_documents to service_role;

-- Same signature as the function n8n expects (query_embedding, match_count, filter)
create function public.match_rag_documents(query_embedding extensions.vector, match_count integer default null, filter jsonb default '{}'::jsonb)
returns table (id bigint, content text, metadata jsonb, similarity double precision)
language sql
stable
set search_path = ''
as $$
  select d.id, d.content, d.metadata, 1 - (d.embedding operator(extensions.<=>) query_embedding) as similarity
  from public.rag_documents d
  where d.metadata @> coalesce(filter, '{}'::jsonb)
  order by d.embedding operator(extensions.<=>) query_embedding
  limit match_count;
$$;

revoke all on function public.match_rag_documents(extensions.vector, integer, jsonb) from public, anon, authenticated;
grant execute on function public.match_rag_documents(extensions.vector, integer, jsonb) to service_role;
